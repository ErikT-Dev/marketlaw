import { collectDefinedRules } from "./collectDefinedRules.ts";
import type { CoverageException } from "./CoverageException.ts";
import { coversOf } from "./coversOf.ts";
import { forEachScenario } from "./forEachScenario.ts";
import type { HarnessFiles } from "./HarnessFiles.ts";
import { HARNESS_PATHS } from "./HARNESS_PATHS.ts";
import { readCoverageExceptions } from "./readCoverageExceptions.ts";

type Coverage = {
  readonly markdown: string;
  readonly gaps: ReadonlyArray<string>;
};

const INTRODUCTION = [
  "# Coverage",
  "",
  "Every numbered rule against the scenarios that test it. Generated by `npm run harness:check`",
  "from the `covers` lists in `scenarios/*.yaml` and from `coverage-exceptions.yaml`; never edit",
  "it by hand.",
  "",
  "- **Covered:** at least one scenario tests the rule.",
  "- **Checked another way:** no scenario, because the rule is a description, a pointer or data.",
  "  Each one is approved by the owner in `coverage-exceptions.yaml`.",
  "- **Gap:** neither. The harness does not pass while any gap is left.",
  "",
];

function scenarioFilesByRule(
  files: HarnessFiles,
): ReadonlyMap<string, ReadonlyMap<string, number>> {
  const byRule = new Map<string, Map<string, number>>();
  forEachScenario(files, ({ file, scenario }) => {
    const shortName = file.replace(`${HARNESS_PATHS.scenarios}/`, "").replace(".yaml", "");
    for (const rule of coversOf(scenario)) {
      const counts = byRule.get(rule) ?? new Map<string, number>();
      counts.set(shortName, (counts.get(shortName) ?? 0) + 1);
      byRule.set(rule, counts);
    }
  });
  return byRule;
}

function statusOf(scenarioCount: number, exception: CoverageException | undefined): string {
  const approval = exception ? ` *(approved by the owner, ${exception.approved})*` : "";
  if (exception?.kind === "instead") {
    return `Checked another way: ${exception.how}${approval}`;
  }
  if (scenarioCount === 0) {
    return "**Gap**";
  }
  return exception ? `Covered. Also: ${exception.how}${approval}` : "Covered";
}

export function buildCoverage(files: HarnessFiles): Coverage {
  const exceptions = readCoverageExceptions(files.coverageExceptions);
  const byRule = scenarioFilesByRule(files);
  const lines = [...INTRODUCTION];
  const gaps: string[] = [];
  let ruleCount = 0;
  for (const spec of HARNESS_PATHS.ruleSpecs) {
    const text = files.ruleSpecs.find((loaded) => loaded.path === spec.path)?.text ?? "";
    lines.push(`## ${spec.title}`, "", "| Rule | Scenarios | Status |", "|---|---|---|");
    for (const rule of collectDefinedRules(text)) {
      ruleCount += 1;
      const counts = [...(byRule.get(rule) ?? new Map<string, number>()).entries()].sort(
        ([a], [b]) => a.localeCompare(b),
      );
      const status = statusOf(counts.length, exceptions.get(rule));
      if (status === "**Gap**") {
        gaps.push(rule);
      }
      const cell = counts.map(([name, count]) => `${name} (${count})`).join(", ") || "–";
      lines.push(`| ${rule} | ${cell} | ${status} |`);
    }
    lines.push("");
  }
  const scenarioCount = files.scenarioFiles.reduce(
    (total, file) => total + file.scenarios.length,
    0,
  );
  lines.push(
    "## Summary",
    "",
    `- Rules: ${ruleCount}`,
    `- Scenarios: ${scenarioCount}`,
    `- Gaps: ${gaps.length}${gaps.length > 0 ? ` (${gaps.join(", ")})` : ""}`,
    `- Checked another way or also checked another way: ${[...exceptions.keys()].join(", ")}`,
    "",
  );
  return { markdown: lines.join("\n"), gaps };
}
